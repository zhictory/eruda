#!/usr/bin/env python3
"""Regenerate src/lib/cangjieData.js from a licensed 仓耳今楷01 W04 TTF.

Usage:
    python3 build/gen-cangjie-font.py /path/to/仓耳今楷01-W04.ttf

Requires: fontTools[woff] and brotli
    python3 -m pip install 'fontTools[woff]' brotli

Subsets the font to GB2312 common hanzi + ASCII + CJK punctuation, converts to
WOFF2, base64-encodes it and writes src/lib/cangjieData.js (a JS module whose
default export is the base64 string). This keeps eruda a single-file drop-in.
"""
import base64
import os
import sys
import textwrap

from fontTools import subset
from fontTools.ttLib import TTFont


def build_char_set():
    chars = {chr(c) for c in range(0x20, 0x7F)}  # ASCII printable
    for start, end in ((0x3000, 0x303F), (0xFF00, 0xFFEF)):  # CJK punctuation
        chars.update(chr(c) for c in range(start, end + 1))
    for c in range(0x4E00, 0xA000):  # GB2312 level 1 + 2 hanzi
        ch = chr(c)
        try:
            ch.encode("gb2312")
            chars.add(ch)
        except UnicodeEncodeError:
            pass
    return chars


def main(src_ttf):
    here = os.path.dirname(os.path.abspath(__file__))
    out_js = os.path.join(here, "..", "src", "lib", "cangjieData.js")

    font = TTFont(src_ttf)
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    sub = subset.Subsetter(options=options)
    sub.populate(text="".join(sorted(build_char_set())))
    sub.subset(font)
    font.flavor = "woff2"

    from io import BytesIO

    buf = BytesIO()
    font.save(buf)
    woff2 = buf.getvalue()

    b64 = base64.b64encode(woff2).decode("ascii")
    chunks = textwrap.wrap(b64, 120)
    body = "\n".join("  '%s'," % c for c in chunks)
    content = (
        "// Auto-generated by build/gen-cangjie-font.py — do not edit.\n"
        "// GB2312-common subset of TsangerJinKai01 W04 (仓耳今楷01 W04), WOFF2 + base64.\n"
        "const CHUNKS = [\n" + body + "\n]\n\nexport default CHUNKS.join('')\n"
    )
    with open(out_js, "w") as f:
        f.write(content)

    print("woff2 bytes: %d, base64 chars: %d, wrote %s" % (len(woff2), len(b64), out_js))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
